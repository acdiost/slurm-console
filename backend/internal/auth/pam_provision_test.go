type provisioningProvider struct {
	run func(pamauth.Request) (pamauth.Result, error)
}

func (p provisioningProvider) Run(_ context.Context, request pamauth.Request) (pamauth.Result, error) {
	return p.run(request)
}

type pamProvisionFixture struct {
	app            core.App
	host           *pamHost
	modes          []string
	fail           string
	onCapabilities func()
	onProbe        func()
	locked         bool
}

func newPAMProvisionFixture(t *testing.T) *pamProvisionFixture {
	t.Helper()
	t.Setenv("SLURM_CONSOLE_PAM_HELPER", "")
	f := &pamProvisionFixture{app: setupPAMApp(t)}
	f.host = &pamHost{root: t.TempDir(), uid: os.Geteuid(), supported: func() bool { return true }}
	f.host.exclusive = func() (func(), error) {
		if f.locked {
			return nil, errors.New("already locked")
		}
		f.locked = true
		return func() { f.locked = false }, nil
	}
	f.host.process = func(path string) (pamauth.Provider, error) {
		return provisioningProvider{run: func(request pamauth.Request) (pamauth.Result, error) {
			if !f.locked {
				t.Fatal("worker executed without maintenance lock")
			}
			info, err := os.Stat(path)
			if err != nil || info.Mode().Perm()&0100 == 0 {
				t.Fatalf("worker is not executable: %v", err)
			}
			f.modes = append(f.modes, request.Mode)
			if request.Mode == "capabilities" && f.onCapabilities != nil {
				f.onCapabilities()
			}
			if request.Mode == "probe" && f.onProbe != nil {
				f.onProbe()
			}
			if request.Mode == f.fail {
				return pamauth.Result{}, pamauth.ErrUnavailable
			}
			return pamauth.Result{OK: true}, nil
		}}, nil
	}
	pamState(f.app).host = f.host
	RegisterPAMBundle(f.app, fstest.MapFS{"slurm-console-pam-helper": &fstest.MapFile{Data: []byte("bundled-worker")}})
	f.put(t, "/etc/pam.d/password-auth", []byte("# trusted existing host stack\n"), 0644)
	return f
}
func (f *pamProvisionFixture) put(t *testing.T, name string, data []byte, mode os.FileMode) {
	t.Helper()
	path := f.host.path(name)
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, data, mode); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(path, mode); err != nil {
		t.Fatal(err)
	}
}
func (f *pamProvisionFixture) configure(revision int) (PAMStatus, error) {
	return ConfigurePAMSetup(context.Background(), f.app, revision, setupPAMActor(), setupPAMAuthorize)
}
func (f *pamProvisionFixture) assertUncommitted(t *testing.T, previous pamauth.Provider) {
	t.Helper()
	record, err := f.app.FindRecordById(pamSettingsCollection, PAMSettingsID)
	if err != nil || record.GetInt("revision") != 1 || record.GetBool("has_override") || f.app.Store().Get(pamProviderKey) != previous {
		t.Fatalf("failed preparation changed settings/runtime: %v", err)
	}
	if count, _ := f.app.CountRecords("operation_audits"); count != 0 {
		t.Fatal("failed preparation retained success audit")
	}
	if f.locked {
		t.Fatal("maintenance lock was not released")
	}
}

func TestPAMConfigureSelectsHostPolicyFamily(t *testing.T) {
	for _, family := range []string{"password-auth", "common", "system-auth", "authselect"} {
		t.Run(family, func(t *testing.T) {
			f := newPAMProvisionFixture(t)
			if err := os.Remove(f.host.path("/etc/pam.d/password-auth")); err != nil {
				t.Fatal(err)
			}
			authStack, accountStack := family, family
			if family == "common" {
				authStack, accountStack = "common-auth", "common-account"
			}
			if family == "authselect" {
				authStack, accountStack = "password-auth", "password-auth"
				f.put(t, "/etc/authselect/password-auth", []byte("# generated by existing authselect\n"), 0644)
				if err := os.Symlink("../authselect/password-auth", f.host.path("/etc/pam.d/password-auth")); err != nil {
					t.Fatal(err)
				}
			} else {
				f.put(t, "/etc/pam.d/"+authStack, []byte("# existing stack\n"), 0644)
				f.put(t, "/etc/pam.d/"+accountStack, []byte("# existing stack\n"), 0644)
			}
			status, err := f.configure(1)
			if err != nil || !status.Configured || !status.Available || !status.HelperInstalled || !status.PolicyInstalled || status.Revision != 2 {
				t.Fatalf("configure: %+v, %v", status, err)
			}
			policy, err := os.ReadFile(f.host.path(pamAppPolicy))
			if err != nil || !strings.Contains(string(policy), "auth include "+authStack+"\n") || !strings.Contains(string(policy), "account include "+accountStack+"\n") || !strings.Contains(string(policy), "account required pam_nologin.so\n") {
				t.Fatalf("incorrect host policy: %q, %v", policy, err)
			}
			if strings.Join(f.modes, ",") != "capabilities,probe" || f.locked {
				t.Fatalf("verification/lock: %v", f.modes)
			}
			info, err := os.Stat(f.host.path(pamManagedHelper))
			if err != nil || info.Mode().Perm() != 0755 || !f.host.ready(f.host.path(pamManagedHelper), true, false) {
				t.Fatalf("worker permissions: %v", err)
			}
			if count, _ := f.app.CountRecords("operation_audits"); count != 1 {
				t.Fatal("successful configure missing audit")
			}
			record, readErr := f.app.FindRecordById(pamSettingsCollection, PAMSettingsID)
			if readErr != nil || !record.GetBool("has_override") || !record.GetBool("enabled") || record.GetInt("revision") != 2 || f.app.Store().Get(pamProviderKey) == nil {
				t.Fatalf("configured PAM was not saved/activated: %v", readErr)
			}
		})
	}
}

func TestPAMConfigurePreservesCustomPolicyAndWorkerAcrossRepeats(t *testing.T) {
	f := newPAMProvisionFixture(t)
	customPolicy := []byte("# administrator policy\nauth required pam_custom.so custom=1\naccount required pam_custom.so\n")
	f.put(t, pamAppPolicy, customPolicy, 0600)
	customWorker := "/opt/private-pam-worker"
	f.put(t, customWorker, []byte("administrator worker"), 0700)
	t.Setenv("SLURM_CONSOLE_PAM_HELPER", f.host.path(customWorker))
	RegisterPAMBundle(f.app, nil)
	if err := os.Remove(f.host.path("/etc/pam.d/password-auth")); err != nil {
		t.Fatal(err)
	}
	for revision := 1; revision <= 2; revision++ {
		status, err := f.configure(revision)
		if err != nil || !status.Configured || status.Revision != revision+1 {
			t.Fatalf("repeat %d: %+v, %v", revision, status, err)
		}
		policy, _ := os.ReadFile(f.host.path(pamAppPolicy))
		worker, _ := os.ReadFile(f.host.path(customWorker))
		if !bytes.Equal(policy, customPolicy) || string(worker) != "administrator worker" {
			t.Fatal("custom policy/worker changed")
		}
	}
	if _, err := os.Lstat(f.host.path(pamManagedHelper)); !os.IsNotExist(err) {
		t.Fatal("custom worker caused managed helper installation")
	}
}

func TestPAMConfigureRepeatsBundledInstallation(t *testing.T) {
	f := newPAMProvisionFixture(t)
	if _, err := f.configure(1); err != nil {
		t.Fatal(err)
	}
	policyBefore, _ := os.Stat(f.host.path(pamAppPolicy))
	status, err := f.configure(2)
	policyAfter, _ := os.Stat(f.host.path(pamAppPolicy))
	if err != nil || !status.Configured || status.Revision != 3 || !os.SameFile(policyBefore, policyAfter) {
		t.Fatalf("repeat changed existing policy or failed: %+v, %v", status, err)
	}
	entries, err := os.ReadDir(filepath.Dir(f.host.path(pamManagedHelper)))
	if err != nil || len(entries) != 1 || entries[0].Name() != "slurm-console-pam-helper" {
		t.Fatalf("backup/staging artifacts retained: %v, %v", entries, err)
	}
}

func TestPAMConfigurePreflightDoesNotChangeHost(t *testing.T) {
	for _, failure := range []string{"revision", "permission", "revoked-before-write", "runtime", "bundle", "stack", "unsafe-policy", "unsafe-shared", "unsafe-custom-worker", "unsupported", "lock"} {
		t.Run(failure, func(t *testing.T) {
			f := newPAMProvisionFixture(t)
			revision := 1
			authorize := setupPAMAuthorize
			denied := errors.New("permission denied")
			switch failure {
			case "revision":
				revision = 2
			case "permission":
				authorize = func(core.App) error { return denied }
			case "revoked-before-write":
				authorize = func(core.App) error {
					if len(f.modes) > 0 {
						return denied
					}
					return nil
				}
			case "runtime":
				f.fail = "capabilities"
			case "bundle":
				RegisterPAMBundle(f.app, nil)
			case "stack":
				if err := os.Remove(f.host.path("/etc/pam.d/password-auth")); err != nil {
					t.Fatal(err)
				}
			case "unsafe-policy":
				f.put(t, pamAppPolicy, []byte("unsafe"), 0666)
			case "unsafe-shared":
				if err := os.Chmod(f.host.path("/etc/pam.d/password-auth"), 0666); err != nil {
					t.Fatal(err)
				}
			case "unsafe-custom-worker":
				f.put(t, "/opt/custom-worker", []byte("unsafe"), 0777)
				t.Setenv("SLURM_CONSOLE_PAM_HELPER", f.host.path("/opt/custom-worker"))
			case "unsupported":
				f.host.supported = func() bool { return false }
			case "lock":
				f.host.exclusive = func() (func(), error) { return nil, errors.New("busy") }
			}
			_, err := ConfigurePAMSetup(context.Background(), f.app, revision, setupPAMActor(), authorize)
			if err == nil {
				t.Fatal("failed preflight succeeded")
			}
			if (failure == "permission" || failure == "revoked-before-write") && !errors.Is(err, denied) {
				t.Fatalf("permission failure lost: %v", err)
			}
			if failure == "revision" && !errors.Is(err, ErrPAMConflict) {
				t.Fatalf("stale revision: %v", err)
			}
			if _, err := os.Lstat(f.host.path(pamManagedHelper)); !os.IsNotExist(err) {
				t.Fatal("preflight installed helper")
			}
			if _, err := os.Lstat(f.host.path("/usr")); !os.IsNotExist(err) {
				t.Fatal("preflight created helper directories")
			}
			if failure != "unsafe-policy" {
				if _, err := os.Lstat(f.host.path(pamAppPolicy)); !os.IsNotExist(err) {
					t.Fatal("preflight installed policy")
				}
			}
			f.assertUncommitted(t, nil)
		})
	}
}

func TestPAMConfigureFailureAtomicallyRestoresHelperPolicySettingsAndRuntime(t *testing.T) {
	for _, failure := range []string{"probe", "settings", "audit", "permission", "audit-revocation"} {
		t.Run(failure, func(t *testing.T) {
			f := newPAMProvisionFixture(t)
			f.put(t, pamManagedHelper, []byte("old usable worker"), 0750)
			oldInfo, _ := os.Stat(f.host.path(pamManagedHelper))
			previous := &setupPAMProvider{}
			RegisterPAM(f.app, previous)
			denied := errors.New("revoked")
			authorize := setupPAMAuthorize
			revoked := false
			switch failure {
			case "probe":
				f.fail = "probe"
			case "settings":
				f.app.OnRecordUpdate("pam_settings").BindFunc(func(*core.RecordEvent) error { return errors.New("storage failure") })
			case "audit":
				f.app.OnRecordCreate("operation_audits").BindFunc(func(*core.RecordEvent) error { return errors.New("audit failure") })
			case "permission":
				f.onProbe = func() { revoked = true }
			case "audit-revocation":
				f.app.OnRecordCreate("operation_audits").BindFunc(func(e *core.RecordEvent) error { revoked = true; return e.Next() })
			}
			if failure == "permission" || failure == "audit-revocation" {
				authorize = func(core.App) error {
					if revoked {
						return denied
					}
					return nil
				}
			}
			_, err := ConfigurePAMSetup(context.Background(), f.app, 1, setupPAMActor(), authorize)
			if err == nil {
				t.Fatal("failed configure succeeded")
			}
			if revoked && !errors.Is(err, denied) {
				t.Fatalf("revocation not preserved: %v", err)
			}
			worker, _ := os.ReadFile(f.host.path(pamManagedHelper))
			restoredInfo, _ := os.Stat(f.host.path(pamManagedHelper))
			if string(worker) != "old usable worker" || !os.SameFile(oldInfo, restoredInfo) || restoredInfo.Mode().Perm() != 0750 {
				t.Fatal("old helper inode/content/mode not restored")
			}
			if _, err := os.Lstat(f.host.path(pamAppPolicy)); !os.IsNotExist(err) {
				t.Fatal("created policy not removed")
			}
			f.assertUncommitted(t, previous)
		})
	}
}

func TestPAMConfigureRollbackPreservesAdministratorReplacements(t *testing.T) {
	for _, modified := range []string{pamManagedHelper, pamAppPolicy} {
		t.Run(filepath.Base(modified), func(t *testing.T) {
			f := newPAMProvisionFixture(t)
			f.put(t, pamManagedHelper, []byte("previous worker"), 0755)
			f.fail = "probe"
			f.onProbe = func() {
				replacement := f.host.path(modified) + ".admin"
				if err := os.WriteFile(replacement, []byte("administrator replacement"), 0755); err != nil {
					t.Fatal(err)
				}
				if err := os.Rename(replacement, f.host.path(modified)); err != nil {
					t.Fatal(err)
				}
			}
			if _, err := f.configure(1); err == nil {
				t.Fatal("probe failure succeeded")
			}
			actual, _ := os.ReadFile(f.host.path(modified))
			if string(actual) != "administrator replacement" {
				t.Fatal("rollback clobbered administrator replacement")
			}
			f.assertUncommitted(t, nil)
		})
	}
}

func TestPAMConfigureAcceptsTrustedSystemDirectoryLinks(t *testing.T) {
	f := newPAMProvisionFixture(t)
	if err := os.MkdirAll(f.host.path("/var/usrlocal"), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(f.host.path("/usr"), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("../var/usrlocal", f.host.path("/usr/local")); err != nil {
		t.Fatal(err)
	}
	if _, err := f.configure(1); err != nil {
		t.Fatal("trusted CoreOS-style directory link rejected", err)
	}
	if err := os.Chmod(f.host.path("/var/usrlocal"), 0777); err != nil {
		t.Fatal(err)
	}
	if _, err := f.configure(2); !errors.Is(err, ErrPAMUnavailable) {
		t.Fatal("writable resolved directory accepted", err)
	}
}

func TestPAMConfigureLabelsOnlyPublishedFilesAndRollsBackLabelFailure(t *testing.T) {
	for _, existingPolicy := range []bool{false, true} {
		t.Run(map[bool]string{false: "new-policy", true: "custom-policy"}[existingPolicy], func(t *testing.T) {
			f := newPAMProvisionFixture(t)
			f.put(t, pamManagedHelper, []byte("previous worker"), 0755)
			if existingPolicy {
				f.put(t, pamAppPolicy, []byte("custom policy"), 0644)
			}
			f.host.labels = func(_ context.Context, paths []string) error {
				if len(paths) != map[bool]int{false: 2, true: 1}[existingPolicy] || paths[0] != f.host.path(pamManagedHelper) {
					t.Fatalf("unexpected label targets: %v", paths)
				}
				return errors.New("restorecon failed")
			}
			if _, err := f.configure(1); !errors.Is(err, ErrPAMUnavailable) {
				t.Fatal("label failure did not fail configuration", err)
			}
			worker, _ := os.ReadFile(f.host.path(pamManagedHelper))
			if string(worker) != "previous worker" {
				t.Fatal("label failure did not restore helper")
			}
			policy, err := os.ReadFile(f.host.path(pamAppPolicy))
			if existingPolicy && (err != nil || string(policy) != "custom policy") {
				t.Fatal("custom policy changed on label failure", err)
			}
			if !existingPolicy && !os.IsNotExist(err) {
				t.Fatal("new policy retained on label failure")
			}
			f.assertUncommitted(t, nil)
		})
	}
}

func TestPAMConfigurePartialPublicationPreservesPolicyCreatedByAdministrator(t *testing.T) {
	f := newPAMProvisionFixture(t)
	f.put(t, pamManagedHelper, []byte("previous worker"), 0755)
	f.onCapabilities = func() { f.put(t, pamAppPolicy, []byte("administrator policy created during preflight"), 0644) }
	if _, err := f.configure(1); err == nil {
		t.Fatal("concurrent policy creation unexpectedly succeeded")
	}
	worker, _ := os.ReadFile(f.host.path(pamManagedHelper))
	policy, _ := os.ReadFile(f.host.path(pamAppPolicy))
	if string(worker) != "previous worker" || string(policy) != "administrator policy created during preflight" {
		t.Fatal("partial publication failed to restore helper/preserve admin policy")
	}
	f.assertUncommitted(t, nil)
}

func TestPAMConfigureDetectsHostChangesDuringProbeAndAudit(t *testing.T) {
	for _, phase := range []string{"probe", "audit"} {
		t.Run(phase, func(t *testing.T) {
			f := newPAMProvisionFixture(t)
			f.put(t, pamManagedHelper, []byte("previous worker"), 0755)
			replace := func() {
				if err := os.WriteFile(f.host.path(pamAppPolicy), []byte("administrator in-place update"), 0644); err != nil {
					t.Fatal(err)
				}
			}
			if phase == "probe" {
				f.onProbe = replace
			} else {
				f.app.OnRecordCreate("operation_audits").BindFunc(func(e *core.RecordEvent) error { replace(); return e.Next() })
			}
			status, err := f.configure(1)
			if !errors.Is(err, ErrPAMUnavailable) || status.Message == "" {
				t.Fatalf("concurrent host change was committed: %+v, %v", status, err)
			}
			policy, _ := os.ReadFile(f.host.path(pamAppPolicy))
			worker, _ := os.ReadFile(f.host.path(pamManagedHelper))
			if string(policy) != "administrator in-place update" || string(worker) != "previous worker" {
				t.Fatal("concurrent changes were overwritten or prior helper not restored")
			}
			f.assertUncommitted(t, nil)
		})
	}
}
