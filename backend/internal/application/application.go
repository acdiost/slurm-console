package application

import (
	"context"
	"os"

	"github.com/pocketbase/pocketbase"
	"github.com/pocketbase/pocketbase/core"
	"github.com/pocketbase/pocketbase/plugins/migratecmd"

	"slurm-console/backend/internal/api"
	"slurm-console/backend/internal/auth"
	"slurm-console/backend/internal/backup"
	"slurm-console/backend/internal/clusterconfig"
	"slurm-console/backend/internal/jobcontrol"
	"slurm-console/backend/internal/rbac"
	_ "slurm-console/backend/migrations"
)

func New() (*pocketbase.PocketBase, error) {
	app := pocketbase.NewWithConfig(pocketbase.Config{DefaultDataDir: "./pb_data"})
	if err := auth.ConfigurePAM(app); err != nil {
		return nil, err
	}
	if err := auth.ConfigureLDAP(app); err != nil {
		return nil, err
	}
	registry, err := clusterconfig.LoadRegistry(os.Getenv("SLURM_CONSOLE_CLUSTER_PROFILES"))
	if err != nil {
		return nil, err
	}
	connections := clusterconfig.Register(app, registry)
	connectionContext, cancelConnections := context.WithCancel(context.Background())
	app.OnTerminate().BindFunc(func(e *core.TerminateEvent) error { cancelConnections(); return e.Next() })
	// Schema changes are reviewed as Go migrations rather than generated by the dashboard.
	migratecmd.MustRegister(app, app.RootCmd, migratecmd.Config{Automigrate: false})
	app.RootCmd.AddCommand(auth.UsersCommand(app))
	app.RootCmd.AddCommand(rbac.Commands(app))
	app.RootCmd.AddCommand(jobcontrol.Command(app))
	app.RootCmd.AddCommand(backup.Commands(), backup.HealthCommand())
	app.OnServe().BindFunc(func(event *core.ServeEvent) error {
		publicDir := os.Getenv("SLURM_CONSOLE_PUBLIC_DIR")
		if publicDir == "" {
			publicDir = "../frontend/dist"
		}
		api.Register(event.Router, publicDir)
		go connections.CheckEnabled(connectionContext)
		return event.Next()
	})
	return app, nil
}
